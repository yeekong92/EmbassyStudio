//! Code generation for ESP32 chips: an Embassy firmware crate on esp-hal + esp-rtos.
//!
//! Same layout as the STM32 generator (see [`crate::codegen`]): `Cargo.toml` (with a user
//! section), `build.rs`, `.cargo/config.toml` (espflash runner), `rust-toolchain.toml`,
//! a regenerated `src/board.rs` and a `src/main.rs` that belongs to the user. Crate
//! versions follow what `esp-generate` produces for the esp-hal release the chip
//! metadata is read from ([`crate::esp::ESP_HAL_TAG`]).

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::codegen::{GenFile, Policy, USER_SECTION_MARKER, field_name};
use crate::db::Chip;
use crate::esp::{EspChip, display_name};
use crate::project::{PinMode, Project, Pull, Speed, crate_name, ident};

const ESP_HAL: &str = "~1.2.2";
const ESP_RTOS: &str = "0.4.0";
const ESP_BOOTLOADER: &str = "0.6.0";
const ESP_PRINTLN: &str = "0.18.0";
const ESP_BACKTRACE: &str = "0.20.0";
const EMBASSY_EXECUTOR: &str = "0.10.0";
const EMBASSY_TIME: &str = "0.5.0";

pub fn generate(project: &Project, chip: &Chip) -> Vec<GenFile> {
    let fallback = EspChip::default();
    let esp = chip.esp.as_ref().unwrap_or(&fallback);
    let pkg = crate_name(&project.name);
    let mut files = vec![
        GenFile { path: "Cargo.toml".into(), contents: cargo_toml(project, chip, esp, &pkg), policy: Policy::KeepUserSection },
        GenFile { path: "build.rs".into(), contents: build_rs(project.codegen.defmt, esp), policy: Policy::Overwrite },
        GenFile { path: ".cargo/config.toml".into(), contents: cargo_config(project, esp), policy: Policy::Overwrite },
        GenFile { path: "rust-toolchain.toml".into(), contents: toolchain(esp), policy: Policy::Overwrite },
        GenFile { path: "src/board.rs".into(), contents: board_rs(project, chip, esp), policy: Policy::Overwrite },
        GenFile { path: "src/main.rs".into(), contents: main_rs(project), policy: Policy::CreateOnly },
        GenFile { path: ".gitignore".into(), contents: "/target\n".into(), policy: Policy::CreateOnly },
        GenFile { path: "README.md".into(), contents: readme(project, chip, esp, &pkg), policy: Policy::CreateOnly },
    ];
    if project.codegen.vscode {
        files.extend(vscode_files(esp, &pkg));
    }
    files
}

/// CPU clock the project runs at: the user's choice if esp-hal offers it, else the maximum.
pub fn cpu_clock_mhz(project: &Project, esp: &EspChip) -> Option<u32> {
    match project.cpu_clock_mhz {
        Some(f) if esp.cpu_clocks_mhz.contains(&f) => Some(f),
        _ => esp.max_cpu_clock_mhz(),
    }
}

fn cargo_toml(project: &Project, chip: &Chip, esp: &EspChip, pkg: &str) -> String {
    let feat = &esp.feature;
    let (log, executor_log, extra) = if project.codegen.defmt {
        ("\"defmt\"", "\"defmt\"", "defmt = \"1.0.1\"\n")
    } else {
        ("\"log-04\"", "\"log\"", "log = \"0.4.27\"\n")
    };
    let println_fmt = if project.codegen.defmt { "\"defmt-espflash\"" } else { "\"log-04\"" };
    let backtrace_fmt = if project.codegen.defmt { "\"defmt\"" } else { "\"println\"" };
    let mut out = format!(
        r#"# Generated by Embassy Studio for {name}.
# Re-generating rewrites this file except for the user section at the bottom.

[package]
name = "{pkg}"
version = "0.1.0"
edition = "2024"

[[bin]]
name = "{pkg}"
path = "src/main.rs"
test = false
doctest = false
bench = false

[dependencies]
esp-hal = {{ version = "{ESP_HAL}", features = ["{feat}", "unstable", {log}] }}
esp-rtos = {{ version = "{ESP_RTOS}", features = ["{feat}", "embassy", {log}] }}
esp-bootloader-esp-idf = {{ version = "{ESP_BOOTLOADER}", features = ["{feat}", {log}] }}
esp-println = {{ version = "{ESP_PRINTLN}", features = ["{feat}", {println_fmt}] }}
esp-backtrace = {{ version = "{ESP_BACKTRACE}", features = ["{feat}", "panic-handler", {backtrace_fmt}] }}
embassy-executor = {{ version = "{EMBASSY_EXECUTOR}", features = [{executor_log}] }}
embassy-time = {{ version = "{EMBASSY_TIME}", features = [{executor_log}] }}
critical-section = "1.2.0"
{extra}"#,
        name = display_name(&chip.name),
    );
    out.push_str(
        r#"
[profile.dev]
# The default debug profile is too slow and too big for these devices.
opt-level = "s"

[profile.release]
codegen-units = 1
debug = 2
lto = "fat"
opt-level = "s"

"#,
    );
    out.push_str(USER_SECTION_MARKER);
    out.push('\n');
    out
}

fn build_rs(defmt: bool, esp: &EspChip) -> String {
    let defmt = if defmt { "    println!(\"cargo:rustc-link-arg=-Tdefmt.x\");\n" } else { "" };
    let script_arg = if esp.is_xtensa() { "-Wl,--error-handling-script" } else { "--error-handling-script" };
    format!(
        r#"// Generated by Embassy Studio.
fn main() {{
    linker_be_nice();
{defmt}    // linkall.x must be the last linker script.
    println!("cargo:rustc-link-arg=-Tlinkall.x");
}}

/// Turn common link errors into hints (the linker calls this build script back).
fn linker_be_nice() {{
    let args: Vec<String> = std::env::args().collect();
    if args.len() > 2 {{
        let (kind, what) = (&args[1], &args[2]);
        if kind == "undefined-symbol" {{
            let hint = match what.as_str() {{
                w if w.starts_with("_defmt_") => "`defmt` not found: is `defmt.x` passed to the linker and `esp_println` linked?",
                "_stack_start" => "Is the linker script `linkall.x` missing?",
                w if w.starts_with("esp_rtos_") => "esp-rtos is not started: call `esp_rtos::start` (board::init does).",
                "free" | "malloc" | "calloc" => "Add the `esp-alloc` dependency for heap allocations.",
                _ => "",
            }};
            if !hint.is_empty() {{
                eprintln!("\n💡 {{hint}}\n");
            }}
            std::process::exit(0);
        }}
        std::process::exit(1);
    }}
    println!("cargo:rustc-link-arg={script_arg}={{}}", std::env::current_exe().unwrap().display());
}}
"#
    )
}

fn cargo_config(project: &Project, esp: &EspChip) -> String {
    let (env, log_format) = if project.codegen.defmt {
        ("DEFMT_LOG = \"info\"", " --log-format defmt")
    } else {
        ("ESP_LOG = \"info\"", "")
    };
    let rustflags = if esp.is_xtensa() {
        "  \"-C\", \"link-arg=-nostartfiles\",\n"
    } else {
        "  # Required for backtraces (esp-backtrace).\n  \"-C\", \"force-frame-pointers\",\n"
    };
    format!(
        r#"# Generated by Embassy Studio.
[target.{target}]
runner = "espflash flash --monitor --chip {chip}{log_format}"

[env]
{env}

[build]
rustflags = [
{rustflags}]
target = "{target}"

[unstable]
build-std = ["core"]
"#,
        target = esp.target,
        chip = esp.feature,
    )
}

fn toolchain(esp: &EspChip) -> String {
    if esp.is_xtensa() {
        // Xtensa needs Espressif's Rust fork, installed with `espup install`.
        "[toolchain]\nchannel = \"esp\"\n".into()
    } else {
        format!("[toolchain]\nchannel = \"stable\"\ncomponents = [\"rust-src\"]\ntargets = [\"{}\"]\n", esp.target)
    }
}

fn main_rs(project: &Project) -> String {
    let (uses, logger) = if project.codegen.defmt {
        ("use defmt::info;\nuse esp_println as _;\n", "")
    } else {
        ("use log::info;\n", "    esp_println::logger::init_logger_from_env();\n")
    };
    let name = project.name.replace('"', "'");
    let blink = project
        .pins
        .iter()
        .find(|(_, p)| p.mode == PinMode::GpioOutput)
        .map(|(pin, p)| field_name(pin, &p.label));
    let body = match blink {
        Some(field) => format!(
            "    loop {{\n        board.{field}.toggle();\n        info!(\"tick\");\n        Timer::after_millis(500).await;\n    }}\n"
        ),
        None => "    loop {\n        info!(\"tick\");\n        Timer::after_millis(1000).await;\n    }\n".into(),
    };
    format!(
        r#"#![no_std]
#![no_main]

// This file was created by Embassy Studio and is yours to edit;
// it is not overwritten when code is regenerated. Hardware setup lives in board.rs.

mod board;

use embassy_executor::Spawner;
use embassy_time::Timer;
use esp_backtrace as _;
{uses}
// App descriptor required by the ESP-IDF second-stage bootloader.
esp_bootloader_esp_idf::esp_app_desc!();

#[esp_rtos::main]
async fn main(_spawner: Spawner) -> ! {{
{logger}    #[allow(unused_mut, unused_variables)]
    let mut board = board::init();
    info!("{name} started");

{body}}}
"#
    )
}

struct BoardField {
    name: String,
    ty: String,
    init: String,
}

fn board_rs(project: &Project, chip: &Chip, esp: &EspChip) -> String {
    let mut fields: Vec<BoardField> = Vec::new();
    let mut notes: Vec<String> = Vec::new();
    let mut used_names = BTreeSet::new();
    let mut unique = |base: String| -> String {
        let mut name = base.clone();
        let mut i = 2;
        while !used_names.insert(name.clone()) {
            name = format!("{base}_{i}");
            i += 1;
        }
        name
    };
    let mut needs: BTreeSet<&str> = BTreeSet::new();

    // GPIO pins.
    let drive = |s: Speed| match s {
        Speed::Low => Some("_5mA"),
        Speed::Medium => Some("_10mA"),
        Speed::High => None, // esp-hal's default, 20 mA
        Speed::VeryHigh => Some("_40mA"),
    };
    let input_config = |p: Pull| match p {
        Pull::None => "InputConfig::default()".to_string(),
        Pull::Up => "InputConfig::default().with_pull(Pull::Up)".to_string(),
        Pull::Down => "InputConfig::default().with_pull(Pull::Down)".to_string(),
    };
    for (pin, cfg) in &project.pins {
        let name = field_name(pin, &cfg.label);
        let restriction = esp.pin_limits.get(pin).filter(|l| !l.is_empty());
        match &cfg.mode {
            PinMode::GpioOutput => {
                if esp.input_only(pin) {
                    notes.push(format!("{pin} is input-only and cannot be an output. Skipped."));
                    continue;
                }
                let config = match drive(cfg.speed) {
                    Some(d) => {
                        needs.insert("drive");
                        format!("OutputConfig::default().with_drive_strength(DriveStrength::{d})")
                    }
                    None => "OutputConfig::default()".into(),
                };
                needs.insert("output");
                fields.push(BoardField {
                    name: unique(name),
                    ty: "Output<'static>".into(),
                    init: format!("Output::new(p.{pin}, Level::{}, {config})", if cfg.initial_high { "High" } else { "Low" }),
                });
            }
            PinMode::GpioInput | PinMode::ExtiInput => {
                needs.insert("input");
                let mut pull = cfg.pull;
                // Input-only pads (ESP32 GPIO34–39) have no internal pull resistors.
                if pull != Pull::None && esp.input_only(pin) {
                    notes.push(format!("{pin} is input-only and has no internal pull resistor: fit an external one."));
                    pull = Pull::None;
                }
                if pull != Pull::None {
                    needs.insert("pull");
                }
                fields.push(BoardField {
                    name: unique(name),
                    ty: "Input<'static>".into(),
                    init: format!("Input::new(p.{pin}, {})", input_config(pull)),
                });
            }
            PinMode::Analog => notes.push(format!(
                "{pin} ({}) is reserved as analog input: pass `p.{pin}` to `esp_hal::analog::adc`.",
                if cfg.label.is_empty() { "no label" } else { &cfg.label }
            )),
            PinMode::Peripheral { .. } => {}
        }
        if let Some(l) = restriction {
            if l.iter().any(|x| x == "strapping") {
                notes.push(format!("{pin} is a strapping pin: keep its level valid during reset."));
            }
            if esp.reserved(pin) {
                notes.push(format!("{pin} is usually wired to flash/PSRAM ({}); check your module.", l.join(", ")));
            }
        }
    }

    // Peripheral drivers.
    for (name, pcfg) in &project.peripherals {
        if !pcfg.enabled {
            continue;
        }
        let Some(periph) = chip.peripheral(name) else { continue };
        let kind = periph.registers.as_ref().map(|r| r.kind.as_str()).unwrap_or("");
        let pins = project.peripheral_pins(name);
        let pin = |sig: &str| pins.iter().find(|(_, s)| s == sig).map(|(p, _)| format!("p.{p}"));
        let with = |list: &[(&str, &str)]| -> String {
            list.iter()
                .filter_map(|(sig, method)| pin(sig).map(|p| format!(".{method}({p})")))
                .collect()
        };
        let field = unique(ident(name));
        match kind {
            "uart" => {
                if pin("TX").is_none() && pin("RX").is_none() {
                    notes.push(format!("{name}: enabled but no TX/RX pin assigned; driver not created."));
                    continue;
                }
                let baud = project.setting(name, "baudrate").unwrap_or("115200");
                let pins = with(&[("TX", "with_tx"), ("RX", "with_rx"), ("CTS", "with_cts"), ("RTS", "with_rts")]);
                if name == "UART0" {
                    notes.push("UART0 is also the default console of esp-println; logs may share its pins.".into());
                }
                needs.insert("uart");
                fields.push(BoardField {
                    name: field,
                    ty: "Uart<'static, Async>".into(),
                    init: format!(
                        "Uart::new(p.{name}, uart::Config::default().with_baudrate({baud})).unwrap(){pins}.into_async()"
                    ),
                });
            }
            "spi" => {
                if pin("SCK").is_none() || (pin("MOSI").is_none() && pin("MISO").is_none()) {
                    notes.push(format!("{name}: assign SCK plus MOSI and/or MISO to create the SPI driver."));
                    continue;
                }
                let freq = project.setting(name, "frequency").unwrap_or("1000000");
                let pins = with(&[("SCK", "with_sck"), ("MOSI", "with_mosi"), ("MISO", "with_miso"), ("CS0", "with_cs")]);
                needs.insert("spi");
                fields.push(BoardField {
                    name: field,
                    ty: "Spi<'static, Async>".into(),
                    init: format!(
                        "Spi::new(p.{name}, spi::master::Config::default().with_frequency(Rate::from_hz({freq}))).unwrap(){pins}.into_async()"
                    ),
                });
            }
            "i2c" => {
                if pin("SCL").is_none() || pin("SDA").is_none() {
                    notes.push(format!("{name}: assign SCL and SDA to create the I2C driver."));
                    continue;
                }
                let freq = project.setting(name, "frequency").unwrap_or("100000");
                let pins = with(&[("SDA", "with_sda"), ("SCL", "with_scl")]);
                needs.insert("i2c");
                fields.push(BoardField {
                    name: field,
                    ty: "I2c<'static, Async>".into(),
                    init: format!(
                        "I2c::new(p.{name}, i2c::master::Config::default().with_frequency(Rate::from_hz({freq}))).unwrap(){pins}.into_async()"
                    ),
                });
            }
            _ => {
                let module = match kind {
                    "adc" => "esp_hal::analog::adc",
                    "i2s" => "esp_hal::i2s::master",
                    "twai" => "esp_hal::twai",
                    "ledc" => "esp_hal::ledc",
                    "rmt" => "esp_hal::rmt",
                    _ => "esp_hal",
                };
                let pin_list: Vec<String> = pins.iter().map(|(p, s)| format!("{s}={p}")).collect();
                notes.push(format!(
                    "{name} enabled{}: create its driver from `p.{name}` with `{module}`.",
                    if pin_list.is_empty() { String::new() } else { format!(", pins {}", pin_list.join(", ")) }
                ));
            }
        }
    }

    // ---- assemble ----
    let mut out = String::new();
    let _ = writeln!(
        out,
        "//! Board support generated by Embassy Studio for {} ({}, {}).\n//!\n//! DO NOT EDIT: this file is regenerated from embassy-studio.json.\n//! Put application code in main.rs.\n",
        display_name(&chip.name),
        esp.arch,
        esp.target
    );
    let mut uses: Vec<String> = Vec::new();
    if needs.contains("uart") || needs.contains("spi") || needs.contains("i2c") {
        uses.push("Async".into());
    }
    let cpu = cpu_clock_mhz(project, esp);
    if cpu.is_some() {
        uses.push("clock::CpuClock".into());
    }
    let mut gpio = Vec::new();
    if needs.contains("output") {
        gpio.extend(["Level", "Output", "OutputConfig"]);
    }
    if needs.contains("drive") {
        gpio.push("DriveStrength");
    }
    if needs.contains("input") {
        gpio.extend(["Input", "InputConfig"]);
    }
    if needs.contains("pull") {
        gpio.push("Pull");
    }
    gpio.sort();
    if !gpio.is_empty() {
        uses.push(format!("gpio::{{{}}}", gpio.join(", ")));
    }
    if needs.contains("i2c") {
        uses.push("i2c::{self, master::I2c}".into());
    }
    if needs.contains("spi") {
        uses.push("spi::{self, master::Spi}".into());
    }
    if needs.contains("spi") || needs.contains("i2c") {
        uses.push("time::Rate".into());
    }
    uses.push("timer::timg::TimerGroup".into());
    if needs.contains("uart") {
        uses.push("uart::{self, Uart}".into());
    }
    out.push_str("#[allow(unused_imports)]\nuse esp_hal::{\n");
    for u in &uses {
        let _ = writeln!(out, "    {u},");
    }
    out.push_str("};\n\n");

    out.push_str("/// Chip configuration.\npub fn config() -> esp_hal::Config {\n");
    if let Some(x) = esp.xtal_mhz.first().filter(|_| esp.xtal_mhz.len() == 1) {
        let _ = writeln!(out, "    // Crystal: {x} MHz");
    } else if !esp.xtal_mhz.is_empty() {
        let list: Vec<String> = esp.xtal_mhz.iter().map(|x| format!("{x} MHz")).collect();
        let _ = writeln!(out, "    // Crystal: {} (handled by esp-hal)", list.join(" or "));
    }
    match cpu {
        Some(mhz) => {
            let _ = writeln!(out, "    esp_hal::Config::default().with_cpu_clock(CpuClock::_{mhz}MHz)");
        }
        None => out.push_str("    esp_hal::Config::default()\n"),
    }
    out.push_str("}\n\n");

    out.push_str("/// Configured pins and peripherals.\n#[allow(dead_code)]\npub struct Board {\n");
    for f in &fields {
        let _ = writeln!(out, "    pub {}: {},", f.name, f.ty);
    }
    out.push_str("}\n\n");

    out.push_str("/// Initialise the chip, start the Embassy runtime, then create pins and drivers.\npub fn init() -> Board {\n");
    out.push_str("    let p = esp_hal::init(config());\n\n");
    out.push_str("    // esp-rtos: Embassy time driver and scheduler, on timer group 0.\n");
    out.push_str("    let timg0 = TimerGroup::new(p.TIMG0);\n");
    out.push_str("    esp_rtos::start(timg0.timer0, p.FROM_CPU_INTR0);\n\n");
    for note in &notes {
        let _ = writeln!(out, "    // NOTE: {note}");
    }
    out.push_str("    Board {\n");
    for f in &fields {
        let _ = writeln!(out, "        {}: {},", f.name, f.init);
    }
    out.push_str("    }\n}\n");
    out
}

fn readme(project: &Project, chip: &Chip, esp: &EspChip, pkg: &str) -> String {
    let setup = if esp.is_xtensa() {
        "cargo install espup --locked\nespup install            # Xtensa Rust toolchain (`esp` channel)\n# Linux/macOS: . $HOME/export-esp.sh\n"
    } else {
        "# The stable toolchain and the target are installed from rust-toolchain.toml.\n"
    };
    let debug = if esp.usb_serial_jtag {
        "- **Debugging**: the built-in USB Serial/JTAG works with probe-rs (`F5` in VS Code with the\n  *probe-rs debugger* extension)."
    } else {
        "- **Debugging**: connect an external JTAG probe (e.g. ESP-Prog) and use probe-rs (`F5` in VS\n  Code with the *probe-rs debugger* extension)."
    };
    format!(
        r#"# {name}

Embassy firmware for **{chip}** ({arch}, `{target}`), generated by Embassy Studio on
[esp-hal](https://github.com/esp-rs/esp-hal) and esp-rtos.

## Layout

| Path | Owner |
|------|-------|
| `embassy-studio.json` | Embassy Studio project (pins, clocks, peripherals) |
| `src/board.rs` | Generated — regenerated on every *Generate Code* |
| `src/main.rs` | Yours — created once, never overwritten |
| `Cargo.toml` | Generated, except the user section at the bottom |

## Build & flash

```sh
{setup}cargo install espflash --locked
cargo build --release
cargo run --release     # flashes with espflash and opens the serial monitor
```

## IDEs

- **VS Code**: open this folder; install *rust-analyzer*. `Ctrl+Shift+B` builds.
{debug}
  The ELF is `target/{target}/debug/{pkg}`.
"#,
        name = project.name,
        chip = display_name(&chip.name),
        arch = if esp.is_xtensa() { "Xtensa" } else { "RISC-V" },
        target = esp.target,
    )
}

fn vscode_files(esp: &EspChip, pkg: &str) -> Vec<GenFile> {
    let target = &esp.target;
    let extra_env = if esp.is_xtensa() {
        ",\n  \"rust-analyzer.server.extraEnv\": { \"RUSTUP_TOOLCHAIN\": \"stable\" },\n  \"rust-analyzer.cargo.extraEnv\": { \"RUSTUP_TOOLCHAIN\": \"esp\" }"
    } else {
        ""
    };
    let settings = format!(
        r#"{{
  "rust-analyzer.cargo.target": "{target}",
  "rust-analyzer.cargo.allTargets": false,
  "rust-analyzer.check.allTargets": false,
  "editor.formatOnSave": true{extra_env}
}}
"#
    );
    let launch = format!(
        r#"{{
  "version": "0.2.0",
  "configurations": [
    {{
      "type": "probe-rs-debug",
      "request": "launch",
      "name": "Flash & debug ({chip})",
      "cwd": "${{workspaceFolder}}",
      "preLaunchTask": "cargo build",
      "chip": "{chip}",
      "flashingConfig": {{
        "flashingEnabled": true,
        "haltAfterReset": true,
        "formatOptions": {{ "binaryFormat": "idf" }}
      }},
      "coreConfigs": [
        {{
          "coreIndex": 0,
          "programBinary": "target/{target}/debug/{pkg}"
        }}
      ]
    }}
  ]
}}
"#,
        chip = esp.feature
    );
    let tasks = r#"{
  "version": "2.0.0",
  "tasks": [
    {
      "label": "cargo build",
      "type": "cargo",
      "command": "build",
      "problemMatcher": ["$rustc"],
      "group": { "kind": "build", "isDefault": true }
    },
    {
      "label": "cargo run (flash & monitor)",
      "type": "cargo",
      "command": "run",
      "args": ["--release"],
      "problemMatcher": ["$rustc"]
    }
  ]
}
"#;
    let extensions = r#"{
  "recommendations": ["rust-lang.rust-analyzer", "probe-rs.probe-rs-debugger", "tamasfe.even-better-toml"]
}
"#;
    vec![
        GenFile { path: ".vscode/settings.json".into(), contents: settings, policy: Policy::Overwrite },
        GenFile { path: ".vscode/launch.json".into(), contents: launch, policy: Policy::Overwrite },
        GenFile { path: ".vscode/tasks.json".into(), contents: tasks.into(), policy: Policy::Overwrite },
        GenFile { path: ".vscode/extensions.json".into(), contents: extensions.into(), policy: Policy::CreateOnly },
    ]
}
